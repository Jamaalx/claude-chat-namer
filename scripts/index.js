import {
  readFileSync,
  writeFileSync,
  renameSync,
  existsSync,
  readdirSync,
  statSync,
  openSync,
  readSync,
  closeSync,
  mkdirSync,
} from "fs";
import { join, basename, dirname } from "path";
import { homedir } from "os";
import { createInterface } from "readline";
import { fileURLToPath } from "url";

// Claude Code honours CLAUDE_CONFIG_DIR, so do we.
export const CLAUDE_DIR = process.env.CLAUDE_CONFIG_DIR || join(homedir(), ".claude");
export const PROJECTS_DIR = join(CLAUDE_DIR, "projects");
const NAMES_FILE = "chat-names.json";
const CACHE_DIR = join(CLAUDE_DIR, "chat-namer");
const CACHE_FILE = join(CACHE_DIR, "cache.json");
// Bump when the shape of the cached metadata changes.
const CACHE_VERSION = 2;
// What the user typed in one conversation, kept for full-text search.
const MAX_SEARCH_TEXT = 64 * 1024;

export const VERSION = (() => {
  try {
    const pkg = join(dirname(fileURLToPath(import.meta.url)), "..", "package.json");
    return JSON.parse(readFileSync(pkg, "utf-8")).version;
  } catch {
    return "unknown";
  }
})();

// ─── Projects ───────────────────────────────────────────────────────────────

/**
 * Get all project directories inside .claude/projects/
 */
export function getProjects() {
  if (!existsSync(PROJECTS_DIR)) return [];
  return readdirSync(PROJECTS_DIR)
    .filter((f) => {
      try {
        return statSync(join(PROJECTS_DIR, f)).isDirectory();
      } catch {
        return false; // broken symlink, permission error, etc.
      }
    })
    .map((name) => ({
      name,
      path: join(PROJECTS_DIR, name),
      displayName: name.replace(/--/g, "\\").replace(/-/g, " "),
    }));
}

/**
 * Claude Code stores the transcripts of a working directory in
 * ~/.claude/projects/<dir with every non-alphanumeric char replaced by "-">.
 * Return the project for `dir` (or its closest parent that has one).
 */
export function findProjectForDir(projects, dir) {
  let current = dir;
  while (current) {
    const encoded = current.replace(/[^a-zA-Z0-9]/g, "-");
    const match = projects.find((p) => p.name === encoded);
    if (match) return match;
    const parent = dirname(current);
    if (parent === current) break;
    current = parent;
  }
  return null;
}

// ─── Transcript parsing ─────────────────────────────────────────────────────

// Top-level entry types we care about. A nested `"type":"user"` inside a
// string is escaped (\"type\":\"user\"), so requiring a non-backslash before
// the quote keeps us on the top-level key without a full JSON.parse.
const TYPE_RE = /(?:^|[^\\])"type":"(user|assistant|ai-title|agent-name|custom-title|summary)"/;

function emptyMeta() {
  return {
    firstMessage: null,
    messageCount: 0,
    cwd: null,
    nativeTitle: null, // set with /rename inside Claude Code
    aiTitle: null, // generated by Claude Code
    summary: null,
    searchText: "",
  };
}

/**
 * Feed one JSONL line into the running metadata. Order matters: the last
 * title entry wins, the first real user message wins.
 */
function consumeLine(meta, line) {
  const m = TYPE_RE.exec(line);
  if (!m) return;
  const type = m[1];

  if (type === "assistant") {
    // Counting only; skip the (often huge) parse.
    if (!line.includes('"isSidechain":true')) meta.messageCount++;
    return;
  }

  let entry;
  try {
    entry = JSON.parse(line);
  } catch {
    return; // malformed or truncated (file still being written)
  }
  if (entry.type !== type) return;

  switch (type) {
    case "ai-title":
      if (entry.aiTitle) meta.aiTitle = String(entry.aiTitle);
      return;
    case "agent-name":
      if (entry.agentName) meta.nativeTitle = String(entry.agentName);
      return;
    case "custom-title":
      if (entry.customTitle) meta.nativeTitle = String(entry.customTitle);
      return;
    case "summary":
      if (entry.summary) meta.summary = String(entry.summary);
      return;
    case "user": {
      if (entry.isSidechain) return; // subagent traffic, not the conversation
      meta.messageCount++;
      if (!meta.cwd && entry.cwd) meta.cwd = entry.cwd;
      if (entry.isMeta) return;
      const text = extractTextFromMessage(entry.message);
      if (!isRealUserText(text)) return;
      if (!meta.firstMessage) meta.firstMessage = text;
      if (meta.searchText.length < MAX_SEARCH_TEXT) {
        meta.searchText = (meta.searchText + "\n" + text).slice(0, MAX_SEARCH_TEXT);
      }
      return;
    }
  }
}

function scanFile(filePath, meta, start = 0) {
  return scanLines(filePath, (line) => consumeLine(meta, line), start);
}

/**
 * Parse a conversation JSONL file (no cache). Kept for the hook and tests.
 */
export function readTranscript(filePath) {
  const meta = emptyMeta();
  scanFile(filePath, meta, 0);
  return meta;
}

// ─── Metadata cache ─────────────────────────────────────────────────────────

let cache = null;
let cacheDirty = false;

function loadCache() {
  if (cache) return cache;
  try {
    const data = JSON.parse(readFileSync(CACHE_FILE, "utf-8"));
    cache = data.version === CACHE_VERSION ? data : { version: CACHE_VERSION, files: {} };
  } catch {
    cache = { version: CACHE_VERSION, files: {} };
  }
  return cache;
}

export function flushCache() {
  if (!cache || !cacheDirty) return;
  try {
    mkdirSync(CACHE_DIR, { recursive: true });
    // Drop entries whose transcript is gone.
    for (const p of Object.keys(cache.files)) {
      if (!existsSync(p)) delete cache.files[p];
    }
    const tmp = `${CACHE_FILE}.${process.pid}.tmp`;
    writeFileSync(tmp, JSON.stringify(cache), "utf-8");
    renameSync(tmp, CACHE_FILE);
    cacheDirty = false;
  } catch {
    // A cache we cannot write only costs speed.
  }
}

/**
 * Metadata for one transcript. Transcripts are append-only, so when a file
 * only grew we parse just the new bytes.
 */
export function getTranscriptMeta(filePath, stat = statSync(filePath)) {
  const c = loadCache();
  const hit = c.files[filePath];
  if (hit && hit.size === stat.size && hit.mtimeMs === stat.mtimeMs) return hit.meta;

  let meta;
  let offset;
  if (hit && stat.size > hit.offset && hit.ino === stat.ino) {
    meta = { ...hit.meta };
    offset = scanFile(filePath, meta, hit.offset);
  } else {
    meta = emptyMeta();
    offset = scanFile(filePath, meta, 0);
  }
  c.files[filePath] = { size: stat.size, mtimeMs: stat.mtimeMs, ino: stat.ino, offset, meta };
  cacheDirty = true;
  return meta;
}

// ─── Conversations ──────────────────────────────────────────────────────────

/**
 * Get all conversations for a project
 */
export function getConversations(projectPath) {
  if (!existsSync(projectPath)) return [];

  const files = readdirSync(projectPath).filter((f) => f.endsWith(".jsonl"));
  const names = loadNames(join(projectPath, NAMES_FILE));
  const project = basename(projectPath);

  const out = [];
  for (const file of files) {
    const uuid = basename(file, ".jsonl");
    const fullPath = join(projectPath, file);
    let stat;
    let meta;
    try {
      stat = statSync(fullPath);
      meta = getTranscriptMeta(fullPath, stat);
    } catch {
      continue; // vanished or unreadable
    }
    const autoName = generateAutoName(meta.firstMessage) || "Empty conversation";
    const own = names[uuid];
    const conv = {
      uuid,
      file,
      path: fullPath,
      project,
      projectPath,
      cwd: meta.cwd,
      name: own?.name || null,
      auto: Boolean(own?.auto), // named by the Stop hook / `auto`, not by the user
      nativeTitle: meta.nativeTitle,
      aiTitle: meta.aiTitle,
      summary: meta.summary,
      autoName,
      firstMessage: meta.firstMessage,
      searchText: meta.searchText,
      messageCount: meta.messageCount,
      lastModified: stat.mtime,
      size: stat.size,
    };
    Object.assign(conv, resolveTitle(conv));
    out.push(conv);
  }
  flushCache();
  return out.sort((a, b) => b.lastModified - a.lastModified);
}

/**
 * All conversations of every project, newest first.
 */
export function getAllConversations() {
  return getProjects()
    .flatMap((p) => getConversations(p.path))
    .sort((a, b) => b.lastModified - a.lastModified);
}

/**
 * Which name to show, and where it came from:
 *   renamed  – /rename inside Claude Code
 *   named    – set with chat-namer by the user
 *   ai       – title Claude Code generated
 *   summary  – compaction summary
 *   auto     – derived from the first message (by us)
 */
export function resolveTitle(conv) {
  if (conv.nativeTitle) return { title: conv.nativeTitle, source: "renamed" };
  if (conv.name && !conv.auto) return { title: conv.name, source: "named" };
  if (conv.aiTitle) return { title: conv.aiTitle, source: "ai" };
  if (conv.summary) return { title: conv.summary, source: "summary" };
  return { title: conv.name || conv.autoName, source: "auto" };
}

/**
 * Extract text content from a message object
 */
export function extractTextFromMessage(message) {
  if (!message) return null;

  const content = message.content;
  if (typeof content === "string") return content;

  if (Array.isArray(content)) {
    for (const block of content) {
      if (block && block.type === "text" && block.text) {
        return block.text;
      }
    }
  }
  return null;
}

/**
 * Claude Code writes slash commands and their output into the transcript as
 * "user" entries wrapped in <command-name>, <local-command-stdout>, etc.
 * Those are not something the user typed, so they make terrible names.
 */
export function isRealUserText(text) {
  if (!text) return false;
  const t = text.trimStart();
  return !/^<(command-name|command-message|command-args|local-command-stdout|local-command-stderr|local-command-caveat|system-reminder)>/.test(
    t
  );
}

/**
 * Generate a short auto-name from the first message.
 * Returns null when there is nothing usable.
 */
export function generateAutoName(text) {
  if (!text) return null;

  // Clean up the text
  let clean = text
    .replace(/```[\s\S]*?```/g, "[code]") // remove code blocks
    .replace(/\[Request interrupted[^\]]*\]/g, "") // interrupted-turn markers
    .replace(/<[^>]+>/g, "") // strip <tags> (system-reminder, command markup...)
    .replace(/\n+/g, " ") // collapse newlines
    .replace(/\s+/g, " ") // collapse spaces
    .trim();

  if (!clean || clean.length < 3) return null;

  // Take first ~60 chars, break at word boundary
  if (clean.length > 60) {
    clean = clean.substring(0, 60);
    const lastSpace = clean.lastIndexOf(" ");
    if (lastSpace > 30) {
      clean = clean.substring(0, lastSpace);
    }
    clean += "...";
  }

  return clean;
}

// ─── Names persistence ─────────────────────────────────────────────────────

export function loadNames(namesPath) {
  if (!existsSync(namesPath)) return {};
  try {
    return JSON.parse(readFileSync(namesPath, "utf-8"));
  } catch {
    return {};
  }
}

// Write to a temp file and rename it over the original. rename() is atomic on
// the same filesystem, so a reader (e.g. the async Stop hook of another
// session) never sees a half-written file. A half-written file used to parse
// as {} and the next save then wiped every name in the project.
export function saveNames(namesPath, names) {
  const tmp = `${namesPath}.${process.pid}.tmp`;
  writeFileSync(tmp, JSON.stringify(names, null, 2), "utf-8");
  renameSync(tmp, namesPath);
}

/**
 * Set a custom name for a conversation
 */
export function nameConversation(projectPath, uuid, name, { auto = false } = {}) {
  const namesPath = join(projectPath, NAMES_FILE);
  const names = loadNames(namesPath);
  names[uuid] = {
    name,
    namedAt: new Date().toISOString(),
    ...(auto ? { auto: true } : {}),
  };
  saveNames(namesPath, names);
  return true;
}

/**
 * Remove a custom name
 */
export function unnameConversation(projectPath, uuid) {
  const namesPath = join(projectPath, NAMES_FILE);
  const names = loadNames(namesPath);
  delete names[uuid];
  saveNames(namesPath, names);
  return true;
}

// ─── Search ─────────────────────────────────────────────────────────────────

/**
 * Search conversations by title or by anything the user typed in them.
 * Every word of the query must match (in any order). Title hits rank first.
 * Each result gets `match` ("title" | "content") and, for content hits,
 * a `snippet` around the first match.
 */
export function searchConversations(projectPathOrConvs, query) {
  const conversations = Array.isArray(projectPathOrConvs)
    ? projectPathOrConvs
    : getConversations(projectPathOrConvs);
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];

  const results = [];
  for (const c of conversations) {
    const titles = [c.title, c.name, c.nativeTitle, c.aiTitle, c.summary, c.autoName]
      .filter(Boolean)
      .join(" \u0000 ")
      .toLowerCase();
    const body = (c.searchText || c.firstMessage || "").toLowerCase();
    const all = titles + " \u0000 " + body;
    if (!words.every((w) => all.includes(w))) continue;

    if (words.every((w) => titles.includes(w))) {
      results.push({ ...c, match: "title", rank: 0 });
    } else {
      results.push({ ...c, match: "content", rank: 1, snippet: makeSnippet(c.searchText || c.firstMessage || "", words) });
    }
  }
  return results.sort((a, b) => a.rank - b.rank || b.lastModified - a.lastModified);
}

function makeSnippet(text, words) {
  const lower = text.toLowerCase();
  let at = -1;
  let len = 0;
  for (const w of words) {
    const i = lower.indexOf(w);
    if (i !== -1 && (at === -1 || i < at)) {
      at = i;
      len = w.length;
    }
  }
  if (at === -1) return null;
  const from = Math.max(0, at - 40);
  const to = Math.min(text.length, at + len + 60);
  return (
    (from > 0 ? "…" : "") +
    text.slice(from, to).replace(/\s+/g, " ").trim() +
    (to < text.length ? "…" : "")
  );
}

/**
 * Auto-name all unnamed conversations in a project
 */
export function autoNameAll(projectPath) {
  const conversations = getConversations(projectPath);
  let named = 0;

  for (const conv of conversations) {
    if (!conv.name && conv.autoName && conv.autoName !== "Empty conversation") {
      nameConversation(projectPath, conv.uuid, conv.autoName, { auto: true });
      named++;
    }
  }

  return named;
}

// ─── Resume / recap ─────────────────────────────────────────────────────────

export function shellQuote(s) {
  return /^[A-Za-z0-9_./:@%+=,-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`;
}

const isWindowsPath = (p) => /^[A-Za-z]:[\\/]/.test(p);

/**
 * `claude --resume` only finds a session from the directory it was started
 * in, so the command includes the `cd`.
 */
export function resumeCommand(conv) {
  const resume = `claude --resume ${conv.uuid}`;
  if (!conv.cwd) return resume;
  // PowerShell (the usual Windows shell for Claude Code) has no reliable &&.
  if (isWindowsPath(conv.cwd)) return `cd "${conv.cwd}"; ${resume}`;
  return `cd ${shellQuote(conv.cwd)} && ${resume}`;
}

/**
 * Find conversations by full UUID, UUID prefix, or search query.
 */
export function findConversations(conversations, ref) {
  if (!ref) return [];
  const byId = conversations.filter((c) => c.uuid.startsWith(ref));
  if (byId.length && /^[0-9a-f-]{4,}$/i.test(ref)) return byId;
  return searchConversations(conversations, ref);
}

/**
 * The last `turns` exchanges of a conversation as plain text (what the user
 * typed and what Claude answered, no tool traffic), for picking a thread back
 * up in a new session. Bounded by `maxChars`.
 */
export function readRecap(filePath, { turns = 12, maxChars = 12000 } = {}) {
  const items = [];
  // Stream the file, keeping the last text turns in a ring buffer.
  const onLine = (line) => {
    const m = TYPE_RE.exec(line);
    if (!m || (m[1] !== "user" && m[1] !== "assistant")) return;
    let entry;
    try {
      entry = JSON.parse(line);
    } catch {
      return;
    }
    if (entry.isSidechain || entry.isMeta) return;
    const content = entry.message?.content;
    let text = null;
    if (typeof content === "string") text = content;
    else if (Array.isArray(content)) {
      text = content
        .filter((b) => b && b.type === "text" && b.text)
        .map((b) => b.text)
        .join("\n");
    }
    if (!text || !text.trim()) return;
    if (entry.type === "user" && !isRealUserText(text)) return;
    items.push({ role: entry.type, text: text.trim(), at: entry.timestamp || null });
    if (items.length > turns * 2) items.shift();
  };
  scanLines(filePath, onLine);

  // Trim from the oldest side until it fits.
  let out = items;
  const size = () => out.reduce((n, i) => n + i.text.length, 0);
  while (out.length > 1 && size() > maxChars) out = out.slice(1);
  if (out.length === 1 && out[0].text.length > maxChars) {
    out = [{ ...out[0], text: "…" + out[0].text.slice(-maxChars) }];
  }
  return out;
}

/**
 * Stream a transcript from byte `start`, calling onLine for every complete
 * line. Returns the offset just after the last complete line, so an
 * incremental re-read never sees half a line (Claude Code always ends lines
 * with "\n"; a dangling tail is a line still being written).
 */
export function scanLines(filePath, onLine, start = 0) {
  const fd = openSync(filePath, "r");
  const CHUNK = 1 << 20;
  const buf = Buffer.alloc(CHUNK);
  let pos = start;
  let lineEnd = start;
  let pending = [];
  try {
    while (true) {
      const n = readSync(fd, buf, 0, CHUNK, pos);
      if (n <= 0) break;
      let from = 0;
      let nl;
      while ((nl = buf.indexOf(10, from)) !== -1 && nl < n) {
        pending.push(buf.subarray(from, nl));
        const line = pending.length === 1 ? pending[0].toString("utf-8") : Buffer.concat(pending).toString("utf-8");
        pending = [];
        if (line.trim()) onLine(line);
        lineEnd = pos + nl + 1;
        from = nl + 1;
      }
      if (from < n) pending.push(Buffer.from(buf.subarray(from, n)));
      pos += n;
    }
  } finally {
    closeSync(fd);
  }
  return lineEnd;
}

// ─── Formatting helpers ─────────────────────────────────────────────────────

const TAGS = {
  renamed: "\x1b[32m[renamed]\x1b[0m",
  named: "\x1b[32m[named]\x1b[0m",
  ai: "\x1b[36m[ai]\x1b[0m",
  summary: "\x1b[36m[summary]\x1b[0m",
  auto: "\x1b[90m[auto]\x1b[0m",
};

/**
 * Format a conversation for display
 */
export function formatConversation(conv, index, { showProject = false } = {}) {
  const date = conv.lastModified.toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
  const sizeKb = (conv.size / 1024).toFixed(0);
  const tag = TAGS[conv.source] || TAGS.auto;
  const where = showProject ? ` | ${conv.cwd || conv.project}` : "";
  const machine = conv.machine ? `\x1b[35m[${conv.machine}]\x1b[0m ` : "";

  let out = `  ${String(index + 1).padStart(3)}. ${machine}${tag} ${conv.title}\n       ${date} | ${conv.messageCount} msgs | ${sizeKb} KB${where} | ${conv.uuid}`;
  if (conv.snippet) out += `\n       \x1b[90m"${conv.snippet}"\x1b[0m`;
  return out;
}

// ─── Interactive CLI helpers ────────────────────────────────────────────────

export function createPrompt() {
  return createInterface({
    input: process.stdin,
    output: process.stdout,
  });
}

export function ask(rl, question) {
  return new Promise((resolve) => {
    rl.question(question, resolve);
  });
}
